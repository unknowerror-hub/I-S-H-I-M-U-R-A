def print_help():
    """ Вывод справки по командам согласно флагу --help """
    print_logo()
    print("\033[93mИспользование:\033[0m")
    print("  python3 kuruma.py [команда] [аргументы]\n")
    print("\033[93mДоступные директивы командной строки:\033[0m")
    print("  \033[92m--help\033[0m               Вывести данное руководство пользователя.")
